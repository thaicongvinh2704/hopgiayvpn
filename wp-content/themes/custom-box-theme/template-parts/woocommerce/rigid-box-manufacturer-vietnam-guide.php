                <h2>Specify Greyboard, Wrap and Insert as One System</h2>
                <p><strong>Greyboard thickness alone does not define box performance.</strong> Board stiffness, flatness, moisture response, grain behavior, box dimensions, joints and product load all affect the finished structure. Ask the manufacturer to return the proposed grade, controlled thickness or tolerance and any substitution rule in the quotation.</p>
                <p>The wrap must work with the board, adhesive, corners and finish. Printed art paper supports detailed graphics; specialty and textured papers change folding and scuff behavior; kraft or recycled-content directions require the same physical approval. Inserts should be selected around retention, presentation, removal, surface protection and disposal requirements.</p>
            </div>
            <div>
                <h2>Control Artwork, Color and Premium Finishes</h2>
                <p>Build artwork on the approved production layout and identify visible panels, wrap turns, joints, hinge areas, insert edges and critical alignment points. Separate CMYK, spot color, foil, embossing, debossing, spot UV and variable-data layers. A digital proof checks content; a physical reference or printed sample is more useful when substrate and finish affect appearance.</p>
                <p>Color approval should name the reference, lighting or viewing condition, substrate and acceptable variation. The <a href="https://www.iso.org/standard/57816.html" target="_blank" rel="noopener noreferrer">ISO 12647 framework</a> explains why print conditions need defined process parameters; the project still needs an agreed practical approval method for its paper and finishes.</p>
            </div>
