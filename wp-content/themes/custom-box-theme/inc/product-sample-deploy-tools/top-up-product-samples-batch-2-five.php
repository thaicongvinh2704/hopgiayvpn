foreach ( $sections as $slug => $product_sections ) {
	$post = get_page_by_path( $slug, OBJECT, 'product' );
	if ( ! $post ) {
		echo "Missing {$slug}\n";
		continue;
	}

	$extra = "\n\n";
	foreach ( $product_sections as $heading => $paragraphs ) {
		$extra .= '<h2>' . esc_html( $heading ) . "</h2>\n";
		foreach ( $paragraphs as $paragraph ) {
			$extra .= '<p>' . esc_html( $paragraph ) . "</p>\n";
		}
	}

	wp_update_post(
		array(
			'ID'           => $post->ID,
			'post_content' => rtrim( $post->post_content ) . $extra,
		)
	);

	if ( function_exists( 'wc_delete_product_transients' ) ) {
		wc_delete_product_transients( $post->ID );
	}

	echo 'Topped up: ' . $post->post_title . PHP_EOL;
}
